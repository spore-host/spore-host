// IAM coverage gate, steps 2-3: map the bundle's SDK commands through the
// closed table, and compare the result with the checked-in inventory.
//
// The inventory (iam/inventory.json) is the reviewable record of what the
// shipped portal can ask AWS to do. It fails the gate when stale, so a change
// that adds an AWS call cannot merge without the inventory diff, which is
// where a reviewer sees it. Regenerate with `npm run portal:iam:update`.
import type { CommandMapping } from "./command-actions.js";

export interface Inventory {
  $comment?: string;
  commands: { command: string; actions: string[] }[];
  actions: string[];
}

export const INVENTORY_COMMENT =
  "Generated by `npm run portal:iam:update` from the production bundle (portal/build/sdk-commands-plugin.ts) through the closed table in portal/iam/command-actions.ts. Do not edit by hand: the IAM gate fails when this file does not match the bundle.";

export interface MapResult {
  inventory: Inventory;
  unmapped: string[];
  problems: string[];
}

/** Map bundle commands through the table. Unmapped commands and empty mappings without a reason are problems. */
export function buildInventory(commands: string[], table: Readonly<Record<string, CommandMapping>>): MapResult {
  const unmapped: string[] = [];
  const problems: string[] = [];
  const rows: Inventory["commands"] = [];
  for (const c of [...new Set(commands)].sort()) {
    const m = table[c];
    if (!m) {
      unmapped.push(c);
      continue;
    }
    if (m.actions.length === 0 && !m.why?.trim()) problems.push(`${c} maps to no IAM action and gives no reason`);
    for (const a of m.actions) if (!/^[a-z0-9-]+:[A-Za-z0-9*]+$/.test(a)) problems.push(`${c}: "${a}" is not an IAM action`);
    rows.push({ command: c, actions: [...m.actions].sort() });
  }
  for (const c of unmapped) problems.push(`${c} is in the bundle but not in portal/iam/command-actions.ts: add it, with the actions it needs, or remove the call`);
  const actions = [...new Set(rows.flatMap((r) => r.actions))].sort();
  return { inventory: { $comment: INVENTORY_COMMENT, commands: rows, actions }, unmapped, problems };
}

/** Differences between the checked-in inventory and the one the bundle implies. Empty means current. */
export function inventoryDrift(checkedIn: Inventory, current: Inventory): string[] {
  const out: string[] = [];
  const key = (r: { command: string; actions: string[] }) => `${r.command} -> [${r.actions.join(", ")}]`;
  const a = new Set(checkedIn.commands.map(key));
  const b = new Set(current.commands.map(key));
  for (const k of b) if (!a.has(k)) out.push(`bundle has ${k}, inventory does not`);
  for (const k of a) if (!b.has(k)) out.push(`inventory has ${k}, bundle does not`);
  const ca = checkedIn.actions.join(",");
  const cb = current.actions.join(",");
  if (ca !== cb) out.push(`inventory actions [${checkedIn.actions.join(", ")}] differ from bundle actions [${current.actions.join(", ")}]`);
  return out;
}

export function serialiseInventory(inv: Inventory): string {
  return `${JSON.stringify({ $comment: INVENTORY_COMMENT, commands: inv.commands, actions: inv.actions }, null, 2)}\n`;
}
